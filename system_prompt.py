def get_system_prompt(tools: list) -> str:
    tool_names = [tool["function"]["name"] for tool in tools]
    return f"""
אתה עוזר חכם המשתמש בכלים חיצוניים כדי לענות על שאלות המשתמש. 
עליך תמיד להשתמש באחד הכלים שהוגדרו במערכת ({', '.join(tool_names)}) כדי לספק תשובה.

מטרתך היא לבחור את הכלי המתאים ביותר לענות על השאלה של הלקוחץ.
כאשר אתה מציג קישורים שהוחזרו מהכלי, העתק אותם במדויק וללא שינוי."""


